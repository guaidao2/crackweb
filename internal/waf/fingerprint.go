// Identify names the WAF behind a response, or "" when nothing is recognised.
func Identify(resp *httpmsg.Response) string {
	if resp == nil {
		return ""
	}
	for _, vendor := range vendors {
		if vendor.identifies(resp) {
			return vendor.Name
		}
	}
	return ""
}

// identifies reports whether a response carries this vendor's fingerprint.
func (v vendorPattern) identifies(resp *httpmsg.Response) bool {
	for _, name := range v.Headers {
		if strings.HasSuffix(name, "*") {
			prefix := strings.TrimSuffix(name, "*")
			for _, field := range resp.Header.All() {
				if strings.HasPrefix(strings.ToLower(field.Name), prefix) {
					return true
				}
			}
			continue
		}
		if resp.Header.Has(name) {
			return true
		}
	}
	for name, want := range v.HeaderValues {
		if containsFold(resp.Header.Get(name), want) {
			return true
		}
	}
	if v.ServerContains != "" && containsFold(resp.Header.Get("Server"), v.ServerContains) {
		return true
	}
	if len(resp.Body) > 0 && len(resp.Body) < 1<<20 {
		body := string(resp.Body)
		for _, marker := range v.BodyMarkers {
			if containsFold(body, marker) {
				return true
			}
		}
	}
	return false
}

// Classify decides whether a probe response indicates a WAF, comparing it
// against the response to a harmless request.
//
// The rule is deliberately strict. A block status code that the baseline did
// not produce is the primary signal; vendor fingerprints and refusal wording
// confirm it. Anything weaker — "the two responses differ" — is not used,
// because applications answer differently for their own reasons and a wrong
// verdict costs four generations of wasted mutation on every later payload.
func Classify(baseline, probe *httpmsg.Response) (blocked bool, vendor string, signature Signature) {
	if probe == nil {
		return false, "", Signature{}
	}

	vendor = Identify(probe)

	// A vendor fingerprint on the refusal is conclusive on its own.
	if vendor != "" && probe.Status >= 400 {
		return true, vendor, Signature{
			Statuses:    []int{probe.Status},
			BodyMarkers: refusalMarkers(probe),
		}
	}

	baselineStatus := 0
	if baseline != nil {
		baselineStatus = baseline.Status
	}
	if probe.Status == baselineStatus || !containsInt([]int{403, 406, 419, 501, 999}, probe.Status) {
		return false, vendor, Signature{}
	}

	// The status changed to a block code. Confirm it reads like a refusal
	// rather than an application-level authorisation failure.
	markers := refusalMarkers(probe)
	if len(markers) > 0 {
		return true, vendor, Signature{Statuses: []int{probe.Status}, BodyMarkers: markers}
	}
	return false, vendor, Signature{}
}

// refusalMarkers returns the refusal wording present in a response, which
// becomes the signature later responses are matched against.
func refusalMarkers(resp *httpmsg.Response) []string {
	if resp == nil || len(resp.Body) == 0 {
		return nil
	}
	body := string(resp.Body)
	var found []string
	for _, marker := range []string{
		"Access Denied", "Request Rejected", "Not Acceptable", "Request blocked",
		"blocked", "forbidden", "security policy", "incident",
		"请求被拦截", "访问被拒绝", "非法请求", "拦截",
	} {
		if containsFold(body, marker) {
			found = append(found, marker)
		}
	}
	return found
}

// containsInt reports whether a slice holds an int.
func containsInt(values []int, want int) bool {
	for _, v := range values {
		if v == want {
			return true
		}
	}
	return false
}

// containsFold reports whether haystack contains needle, case-insensitively.
func containsFold(haystack, needle string) bool {
	if needle == "" {
		return false
	}
	if len(haystack) < len(needle) {
		return false
	}
	// ASCII-lowercase both sides. Vendor markers that contain non-ASCII (the
	// Chinese ones) are compared byte-for-byte, which is correct because their
	// UTF-8 bytes are already lower-case in the sense that matters.
	lowerHaystack := strings.ToLower(haystack)
	lowerNeedle := strings.ToLower(needle)
	return strings.Contains(lowerHaystack, lowerNeedle)
}
