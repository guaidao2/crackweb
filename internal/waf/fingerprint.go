// Signature describes what a refusal looks like from a particular target.
type Signature struct {
	// Statuses are the status codes this target uses to refuse.
	Statuses []int
	// BodyMarkers are substrings that appear in a refusal page.
	BodyMarkers []string
	// HeaderMarkers are response headers that appear only on a refusal.
	HeaderMarkers []string
}

// defaultSignature is the fallback when nothing more specific is known.
func defaultSignature() Signature {
	return Signature{
		Statuses: []int{403, 406, 501, 999},
		BodyMarkers: []string{
			"access denied", "request rejected", "not acceptable",
			"blocked", "forbidden", "security policy",
			"请求被拦截", "访问被拒绝", "非法请求",
		},
	}
}

// matches reports whether a response satisfies this signature.
//
// The status code alone is not enough: applications return 403 for their own
// authorisation failures, and escalating payloads because a page said "no" to
// a different question would burn requests without gaining anything. A status
// code must therefore be accompanied by something that reads like a refusal.
func (s Signature) matches(resp *httpmsg.Response) bool {
	if resp == nil {
		return false
	}
	if !containsInt(s.Statuses, resp.Status) {
		return false
	}
	for _, marker := range s.BodyMarkers {
		if containsFold(string(resp.Body), marker) {
			return true
		}
	}
	for _, name := range s.HeaderMarkers {
		if resp.Header.Has(name) {
			return true
		}
	}
	// A block status with a tiny body is a bare refusal even without wording:
	// real applications send an HTML error page, WAFs send a stub.
	if len(resp.Body) < 512 && resp.Status != 403 {
		return true
	}
	return false
}

// genericBlock is the conservative test used when no WAF was identified.
func genericBlock(resp *httpmsg.Response) bool {
	if resp == nil || !containsInt([]int{403, 406, 501, 999}, resp.Status) {
		return false
	}
	body := strings.ToLower(string(resp.Body))
	for _, marker := range []string{
		"access denied", "request rejected", "not acceptable", "blocked",
		"security policy", "incident id", "ray id",
		"请求被拦截", "访问被拒绝",
	} {
		if strings.Contains(body, marker) {
			return true
		}
	}
	// A refusal stub with no wording at all, from a status code only a WAF
	// uses. 403 is excluded because applications use it for their own denials.
	if resp.Status == 406 || resp.Status == 501 || resp.Status == 999 {
		return len(resp.Body) < 1024
	}
	return false
}

